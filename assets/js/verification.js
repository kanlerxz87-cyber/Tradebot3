/**
 * Tradebot3 — verification page: live provenance + legacy audit summary.
 */

import { SITE, initChrome, qs, esc, fmtNum, fmtDateTime, timeAgo, fmtUsd, fmtContracts } from './core.js';

initChrome({ active: 'verification.html' });

async function load() {
  const status = qs('#verification-status');
  const summary = qs('#audit-summary');
  let snap = null;
  let audit = null;
  try {
    const res = await fetch(`${SITE.dataFile}?v=${Date.now()}`, { cache: 'no-store' });
    if (res.ok) snap = await res.json();
  } catch { /* handled below */ }
  try {
    const res = await fetch(`${SITE.legacyAuditFile}?v=${Date.now()}`, { cache: 'no-store' });
    if (res.ok) audit = await res.json();
  } catch { /* handled below */ }

  if (snap) {
    const s = snap.stats || {};
    status.innerHTML = `
      <span><strong>Snapshot generated</strong> ${esc(fmtDateTime(snap.generated_at))} UTC (${esc(timeAgo(snap.generated_at))})</span>
      <span class="sep">|</span>
      <span>${fmtNum(s.series_discovered || 0)} series discovered · ${fmtNum(s.open_market_scanned || s.open_markets_scanned || 0)} open markets scanned</span>
      <span class="sep">|</span>
      <span>${fmtNum(s.markets_published || 0)} markets published · ${fmtNum(s.alerts_published || 0)} alerts · ${fmtNum(s.resolutions_published || 0)} settlements</span>
      <span class="sep">|</span>
      <a href="${esc(snap.api_base)}" target="_blank" rel="noopener noreferrer">API base</a>
      <span class="tiny">· generated by ${esc(snap.generator || '')}</span>`;
  } else {
    status.innerHTML = '<span class="status-err">Snapshot not available.</span> The scheduled data job may not have run yet.';
  }

  if (audit) {
    const missing = audit.claims_checked - audit.claims_found_in_api;
    summary.innerHTML = `
      <span><strong>Legacy claim audit:</strong> ${fmtNum(audit.claims_found_in_api)} of ${fmtNum(audit.claims_checked)} claimed tickers resolve in the live API</span>
      <span class="sep">|</span>
      <span class="${missing ? 'status-err' : 'status-ok'}">${fmtNum(missing)} claimed tickers do not exist</span>
      <span class="sep">|</span>
      <a href="assets/data/legacy-audit.json" target="_blank" rel="noopener noreferrer">full row-by-row result</a>
      <span class="sep">|</span>
      <a href="flagged-for-review.html">see flagged items</a>`;
  } else {
    summary.innerHTML = '<span class="status-warn">Legacy audit JSON not present yet</span> — it is written by the scheduled data job.';
  }

  if (snap?.official_links) {
    const ol = snap.official_links;
    const st = qs('#links-status');
    if (st) {
      st.innerHTML = `
        <span><strong>${fmtNum(ol.reachable)}</strong> of <strong>${fmtNum(ol.total)}</strong> official links answered when last measured</span>
        <span class="sep">|</span>
        <span class="tiny">checked ${esc(fmtDateTime(ol.checked_at))} UTC (${esc(timeAgo(ol.checked_at))})</span>
        ${ol.unreachable ? `<span class="sep">|</span><span class="status-err">${fmtNum(ol.unreachable)} unreachable — listed on Flagged for review</span>` : ''}`;
    }
    const body = qs('#links-body');
    if (body) {
      body.innerHTML = (ol.rows || []).map((r) => `<tr>
        <td class="tiny">${esc(r.kind)}</td>
        <td>${esc(r.label || '')}</td>
        <td class="tiny"><a href="${esc(r.url)}" target="_blank" rel="noopener noreferrer">${esc(r.url)}</a></td>
        <td class="num">${r.http_status === null ? '<span class="tiny">no response</span>' : esc(r.http_status)}</td>
        <td>${r.reachable
          ? '<span class="badge badge-up">yes</span>'
          : r.http_status === 429
            ? '<span class="badge badge-warn" title="kalshi.com throttled unauthenticated runner burst">throttled (429)</span>'
            : '<span class="badge badge-down">no</span>'}</td>
      </tr>`).join('');
    }
  }

  const cadence = snap?.refresh_cadence;
  const cbox = qs('#cadence-box');
  if (cbox) {
    const m = cadence?.measured;
    const under1h = m ? (m.gaps_under_one_hour ?? m.gaps_under_1h ?? 0) : 0;
    cbox.innerHTML = m
      ? `Measured over <strong>${fmtNum(m.runs_used)}</strong> runs (${esc(fmtDateTime(m.first_run))} → ${esc(fmtDateTime(m.last_run))} UTC):
         median gap <strong>${m.median_gap_hours}h</strong>, mean ${m.mean_gap_hours}h, max ${m.max_gap_hours}h,
         min ${m.min_gap_hours}h; runs closer together than one hour: ${fmtNum(under1h)} of ${fmtNum(m.gap_count)}.
         <div class="tiny" style="margin-top:4px">Source: <a href="assets/data/refresh-history.json" target="_blank" rel="noopener noreferrer">refresh-history.json</a> — written by the workflow itself.</div>`
      : `No measured cadence yet${cadence?.note ? ` — ${esc(cadence.note)}` : ''}.`;
  }

  if (snap?.demo_spot_check?.length) {
    const host = qs('#demo-spot');
    if (host) {
      host.innerHTML = snap.demo_spot_check.map((r) => `<tr>
        <td class="ticker"><a href="https://kalshi.com/events/${encodeURIComponent(String(r.ticker).split('-').slice(0, 2).join('-'))}" target="_blank" rel="noopener noreferrer">${esc(r.ticker)}</a></td>
        <td class="num">${r.prod_last_price === null ? '—' : fmtUsd(r.prod_last_price, 4)}</td>
        <td class="num">${r.demo_last_price === null ? '—' : fmtUsd(r.demo_last_price, 4)}</td>
        <td class="num">${fmtContracts(r.prod_volume)}</td>
        <td class="num">${fmtContracts(r.demo_volume)}</td>
        <td class="tiny"><a href="https://external-api.kalshi.com/trade-api/v2/markets/${encodeURIComponent(r.ticker)}" target="_blank" rel="noopener noreferrer">prod API</a> · <a href="https://external-api.demo.kalshi.co/trade-api/v2/markets/${encodeURIComponent(r.ticker)}" target="_blank" rel="noopener noreferrer">demo API</a></td></tr>`).join('');
    }
  }
}

load();
