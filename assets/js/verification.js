/**
 * Tradebot3 — verification page: live provenance + legacy audit summary.
 */

import { SITE, initChrome, qs, esc, fmtNum, fmtDateTime, timeAgo, fmtUsd, fmtContracts } from './core.js';

initChrome({ active: 'verification.html' });

async function load() {
  const status = qs('#verification-status');
  const summary = qs('#audit-summary');
  let snap = null;
  let audit = null;
  try {
    const res = await fetch(`${SITE.dataFile}?v=${Date.now()}`, { cache: 'no-store' });
    if (res.ok) snap = await res.json();
  } catch { /* handled below */ }
  try {
    const res = await fetch(`${SITE.legacyAuditFile}?v=${Date.now()}`, { cache: 'no-store' });
    if (res.ok) audit = await res.json();
  } catch { /* handled below */ }

  if (snap) {
    const s = snap.stats || {};
    status.innerHTML = `
      <span><strong>Snapshot generated</strong> ${esc(fmtDateTime(snap.generated_at))} UTC (${esc(timeAgo(snap.generated_at))})</span>
      <span class="sep">|</span>
      <span>${fmtNum(s.series_discovered || 0)} series discovered · ${fmtNum(s.open_market_scanned || s.open_markets_scanned || 0)} open markets scanned</span>
      <span class="sep">|</span>
      <span>${fmtNum(s.markets_published || 0)} markets published · ${fmtNum(s.alerts_published || 0)} alerts · ${fmtNum(s.resolutions_published || 0)} settlements</span>
      <span class="sep">|</span>
      <a href="${esc(snap.api_base)}" target="_blank" rel="noopener noreferrer">API base</a>
      <span class="tiny">· generated by ${esc(snap.generator || '')}</span>`;
  } else {
    status.innerHTML = '<span class="status-err">Snapshot not available.</span> The scheduled data job may not have run yet.';
  }

  if (audit) {
    const missing = audit.claims_checked - audit.claims_found_in_api;
    summary.innerHTML = `
      <span><strong>Legacy claim audit:</strong> ${fmtNum(audit.claims_found_in_api)} of ${fmtNum(audit.claims_checked)} claimed tickers resolve in the live API</span>
      <span class="sep">|</span>
      <span class="${missing ? 'status-err' : 'status-ok'}">${fmtNum(missing)} claimed tickers do not exist</span>
      <span class="sep">|</span>
      <a href="assets/data/legacy-audit.json" target="_blank" rel="noopener noreferrer">full row-by-row result</a>
      <span class="sep">|</span>
      <a href="flagged-for-review.html">see flagged items</a>`;
  } else {
    summary.innerHTML = '<span class="status-warn">Legacy audit JSON not present yet</span> — it is written by the scheduled data job.';
  }

  if (snap?.demo_spot_check?.length) {
    const host = qs('#demo-spot');
    if (host) {
      host.innerHTML = snap.demo_spot_check.map((r) => `<tr>
        <td class="ticker"><a href="https://kalshi.com/events/${encodeURIComponent(String(r.ticker).split('-').slice(0, 2).join('-'))}" target="_blank" rel="noopener noreferrer">${esc(r.ticker)}</a></td>
        <td class="num">${r.prod_last_price === null ? '—' : fmtUsd(r.prod_last_price, 4)}</td>
        <td class="num">${r.demo_last_price === null ? '—' : fmtUsd(r.demo_last_price, 4)}</td>
        <td class="num">${fmtContracts(r.prod_volume)}</td>
        <td class="num">${fmtContracts(r.demo_volume)}</td></tr>`).join('');
    }
  }
}

load();
